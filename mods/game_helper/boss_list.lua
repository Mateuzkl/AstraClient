local BOSS_LIST_LOWER = {}
for bossName in pairs(BOSS_LIST) do
  BOSS_LIST_LOWER[bossName:lower()] = true
end

function isBossName(name)
  if not name then return false end
  -- Trim leading/trailing whitespace antes do match.
  -- Servidor as vezes manda nome com espaco/sufixo que faria fallar o lookup.
  local clean = name:lower():gsub("^%s+", ""):gsub("%s+$", "")
  return BOSS_LIST_LOWER[clean] == true
end

-- Publish to the module sandbox env explicitly (same pattern as CreatureCache in
-- creature_cache.lua), so helper.lua resolves isBossName/BOSS_LIST reliably. In
-- Amon this lived in modules/gamelib (a true global); here it ships inside the
-- sandboxed game_helper module and MUST load before `helper` in the .otmod.
_G.BOSS_LIST = BOSS_LIST
_G.isBossName = isBossName